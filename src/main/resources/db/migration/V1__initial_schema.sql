-- Ghunsai Dairy Management - initial schema (PostgreSQL)
-- Use a FRESH database: Flyway owns the schema, Hibernate only validates it.

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL,
    token_version INTEGER      NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    last_login_at TIMESTAMP,
    CONSTRAINT uk_app_users_username UNIQUE (username),
    CONSTRAINT ck_app_users_role CHECK (role IN ('OWNER', 'WORKER'))
);

CREATE TABLE products (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)   NOT NULL,
    category            VARCHAR(50)    NOT NULL,
    unit                VARCHAR(20)    NOT NULL,
    selling_price       NUMERIC(10, 2) NOT NULL,
    active              BOOLEAN        NOT NULL,
    low_stock_threshold NUMERIC(12, 3) NOT NULL,
    CONSTRAINT ck_products_price CHECK (selling_price > 0),
    CONSTRAINT ck_products_threshold CHECK (low_stock_threshold >= 0)
);

CREATE TABLE product_price_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT         NOT NULL REFERENCES products (id),
    selling_price  NUMERIC(12, 2) NOT NULL,
    effective_from TIMESTAMP      NOT NULL,
    CONSTRAINT ck_price_history_price CHECK (selling_price > 0)
);
CREATE INDEX ix_price_history_product ON product_price_history (product_id, effective_from DESC);

CREATE TABLE customers (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(100) NOT NULL,
    phone  VARCHAR(15),
    active BOOLEAN      NOT NULL
);

CREATE TABLE sales (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_date         TIMESTAMP      NOT NULL,
    total_amount      NUMERIC(12, 2) NOT NULL,
    cash_amount       NUMERIC(12, 2) NOT NULL,
    upi_amount        NUMERIC(12, 2) NOT NULL,
    udhaar_amount     NUMERIC(12, 2) NOT NULL,
    customer_id       BIGINT REFERENCES customers (id),
    created_by        BIGINT         NOT NULL REFERENCES app_users (id),
    client_request_id VARCHAR(64),
    CONSTRAINT ck_sales_amounts CHECK (total_amount >= 0 AND cash_amount >= 0
                                       AND upi_amount >= 0 AND udhaar_amount >= 0),
    CONSTRAINT ck_sales_split CHECK (cash_amount + upi_amount + udhaar_amount = total_amount),
    CONSTRAINT ck_sales_udhaar_customer CHECK (udhaar_amount = 0 OR customer_id IS NOT NULL)
);
CREATE INDEX ix_sales_date ON sales (sale_date);
CREATE INDEX ix_sales_customer ON sales (customer_id);
CREATE INDEX ix_sales_created_by ON sales (created_by, sale_date);
-- A retried request (same user + same client_request_id) can never create a second bill.
CREATE UNIQUE INDEX uk_sales_creator_request ON sales (created_by, client_request_id)
    WHERE client_request_id IS NOT NULL;

CREATE TABLE sale_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       BIGINT         NOT NULL REFERENCES sales (id),
    product_id    BIGINT         NOT NULL REFERENCES products (id),
    quantity      NUMERIC(12, 3) NOT NULL,
    selling_price NUMERIC(12, 2) NOT NULL,
    subtotal      NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_sale_items_qty CHECK (quantity > 0),
    CONSTRAINT ck_sale_items_price CHECK (selling_price >= 0)
);
CREATE INDEX ix_sale_items_sale ON sale_items (sale_id);
CREATE INDEX ix_sale_items_product ON sale_items (product_id);

CREATE TABLE customer_payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT         NOT NULL REFERENCES customers (id),
    amount       NUMERIC(12, 2) NOT NULL,
    payment_date TIMESTAMP      NOT NULL,
    notes        VARCHAR(250),
    recorded_by  BIGINT         NOT NULL REFERENCES app_users (id),
    CONSTRAINT ck_customer_payments_amount CHECK (amount > 0)
);
CREATE INDEX ix_customer_payments_customer ON customer_payments (customer_id, payment_date DESC);

CREATE TABLE stock_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT         NOT NULL REFERENCES products (id),
    movement_type VARCHAR(20)    NOT NULL,
    quantity      NUMERIC(12, 3) NOT NULL,
    created_at    TIMESTAMP      NOT NULL,
    notes         VARCHAR(255),
    created_by    BIGINT         NOT NULL REFERENCES app_users (id),
    CONSTRAINT ck_stock_movements_qty CHECK (quantity > 0),
    CONSTRAINT ck_stock_movements_type CHECK (movement_type IN
        ('PURCHASE', 'SALE', 'WASTAGE', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT'))
);
CREATE INDEX ix_stock_movements_product ON stock_movements (product_id);
CREATE INDEX ix_stock_movements_created ON stock_movements (created_at);
